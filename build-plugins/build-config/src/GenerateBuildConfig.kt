package com.chow.pomegranate.build

import org.jetbrains.amper.plugins.Input
import org.jetbrains.amper.plugins.Output
import org.jetbrains.amper.plugins.TaskAction
import java.nio.file.Files
import java.nio.file.Path

@TaskAction
fun generateBuildConfig(@Input catalogFile: Path, @Output outputDirectory: Path) {
    val version = Regex("""(?m)^versionName\s*=\s*"([^"]+)"\s*$""")
        .find(Files.readString(catalogFile))?.groupValues?.get(1)
        ?: error("versionName is missing from $catalogFile")
    require(version.matches(Regex("[0-9A-Za-z+._-]+"))) { "Invalid application version" }
    val target = outputDirectory.resolve("com/chow/pomegranate/BuildConfig.kt")
    Files.createDirectories(target.parent)
    Files.writeString(target, """
        // Generated by the Pomegranate build-config plugin. Do not edit.
        package com.chow.pomegranate

        public object BuildConfig {
            public const val versionName: String = "$version"
        }
    """.trimIndent() + "\n")
}
